"""Фильтр качества PDF перед ingest.

Цель: выкинуть документы которые добавят только шум в Qdrant:
  - сканы без OCR / figures-only статьи (мало слов, много страниц)
  - повреждённые PDF где извлеклось 2-3 слова
  - очень короткие (< N слов) — вероятно обложка журнала или corrigendum

Ничего не удаляет физически: перемещает в `rejected_pdfs/` и логирует причину.
Пользователь может их проверить и при желании вернуть.
"""
from __future__ import annotations

import os
import shutil
from dataclasses import dataclass


# Пороги по умолчанию — тюнятся через env
МИНИМУМ_СЛОВ = int(os.getenv("QUALITY_MIN_WORDS", "200"))
МИНИМУМ_СРЕДНИХ_СИМВ_НА_СТРАНИЦУ = int(os.getenv("QUALITY_MIN_CHARS_PER_PAGE", "300"))
МИНИМУМ_ДОЛЯ_НЕПУСТЫХ_СТРАНИЦ = float(os.getenv("QUALITY_MIN_NONEMPTY_FRAC", "0.3"))


@dataclass
class Результат:
    принят: bool
    причина: str = ""
    слов: int = 0
    страниц: int = 0
    непустых_страниц: int = 0
    средн_символов: float = 0.0


def _сосчитать_слова(текст: str) -> int:
    """Считает слова (split по whitespace), игнорирует одиночные символы."""
    if not текст:
        return 0
    return sum(1 for с in текст.split() if len(с) >= 2)


def _текст_страницы(страница) -> str:
    if len(страница) >= 2:
        return страница[1] or ""
    return ""


def оценить(страницы: list[tuple],
            мин_слов: int | None = None,
            мин_симв_на_страницу: int | None = None,
            мин_доля_непустых: float | None = None) -> Результат:
    """Оценивает качество извлечённого текста.

    страницы: список [(номер, текст), ...] как возвращает ingest_v2.извлечь_pdf
    """
    мин_слов = МИНИМУМ_СЛОВ if мин_слов is None else мин_слов
    мин_симв = МИНИМУМ_СРЕДНИХ_СИМВ_НА_СТРАНИЦУ if мин_симв_на_страницу is None else мин_симв_на_страницу
    мин_доля = МИНИМУМ_ДОЛЯ_НЕПУСТЫХ_СТРАНИЦ if мин_доля_непустых is None else мин_доля_непустых

    страниц_всего = len(страницы)
    if страниц_всего == 0:
        return Результат(принят=False, причина="нет текста вообще",
                         слов=0, страниц=0, непустых_страниц=0)

    тексты = [_текст_страницы(страница) for страница in страницы]
    непустых = sum(1 for т in тексты if len((т or "").strip()) >= 100)
    все_слова = sum(_сосчитать_слова(т) for т in тексты)
    все_символы = sum(len((т or "").strip()) for т in тексты)
    средн_симв = все_символы / страниц_всего if страниц_всего else 0.0

    # Критерий 1: слишком мало слов
    if все_слова < мин_слов:
        return Результат(
            принят=False, причина=f"мало слов ({все_слова} < {мин_слов})",
            слов=все_слова, страниц=страниц_всего, непустых_страниц=непустых,
            средн_символов=средн_симв,
        )

    # Критерий 2: слишком мало непустых страниц (figures/scans)
    if страниц_всего >= 3 and (непустых / страниц_всего) < мин_доля:
        return Результат(
            принят=False,
            причина=f"мало текста на страницах ({непустых}/{страниц_всего}, < {мин_доля:.0%})",
            слов=все_слова, страниц=страниц_всего, непустых_страниц=непустых,
            средн_символов=средн_симв,
        )

    # Критерий 3: средняя плотность текста на странице
    if страниц_всего >= 3 and средн_симв < мин_симв:
        return Результат(
            принят=False,
            причина=f"низкая плотность текста ({средн_симв:.0f} симв/стр < {мин_симв})",
            слов=все_слова, страниц=страниц_всего, непустых_страниц=непустых,
            средн_символов=средн_симв,
        )

    return Результат(
        принят=True, причина="",
        слов=все_слова, страниц=страниц_всего, непустых_страниц=непустых,
        средн_символов=средн_симв,
    )


def отбраковать(путь_оригинал: str, папка_для_отбраковки: str, причина: str) -> str:
    """Перемещает файл в rejected-папку с записью причины в <имя>.reason.txt.

    Возвращает путь куда переместили, или пустую строку при ошибке.
    """
    try:
        os.makedirs(папка_для_отбраковки, exist_ok=True)
        имя = os.path.basename(путь_оригинал)
        новый = os.path.join(папка_для_отбраковки, имя)
        # Если файл с таким именем уже есть в rejected — добавим суффикс
        if os.path.exists(новый):
            база, расш = os.path.splitext(имя)
            for i in range(1, 1000):
                кандидат = os.path.join(папка_для_отбраковки, f"{база}__{i}{расш}")
                if not os.path.exists(кандидат):
                    новый = кандидат
                    break
        # shutil.move, а не os.rename: rejected_pdfs/ может быть на другой
        # файловой системе (например, отдельный том в Docker/CI), где
        # os.rename падает с EXDEV (cross-device link).
        shutil.move(путь_оригинал, новый)
        # Запишем причину
        with open(новый + ".reason.txt", "w", encoding="utf-8") as f:
            f.write(причина + "\n")
        return новый
    except Exception:
        return ""
