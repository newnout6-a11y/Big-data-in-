def детерминировать_язык(текст):
    """Грубое определение языка по доле кириллицы. Без зависимостей."""
    if not текст:
        return "unknown"
    буквы = [с for с in текст if с.isalpha()]
    if not буквы:
        return "unknown"
    кир = sum(1 for с in буквы if "а" <= с.lower() <= "я" or с.lower() == "ё")
    доля = кир / len(буквы)
    if доля > 0.5:
        return "ru"
    if доля < 0.05:
        return "en"
    return "mixed"
