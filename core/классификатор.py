"""Эмбеддинговый классификатор: домен/субдомен + scope-guard.

Без LLM-вызовов — только sentence-transformers.

Идея:
1. Для каждого субдомена из taxonomy.py есть текст-прототип.
2. Один раз эмбеддим прототипы → получаем эталонные векторы.
3. Эмбеддинг любого чанка/вопроса сравниваем cos с прототипами.
4. Top-1 по cos = (домен, субдомен).
5. Scope-guard: если max(cos) ниже порога — off-topic.

Прототипы кэшируются на диск (numpy.npz), чтобы не пересчитывать.
"""
import hashlib
import os

import numpy as np

from taxonomy import все_субдомены


# Файл лежит в core/, prototype_cache.npz — в корне репо.
_БАЗОВАЯ_ПАПКА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_ФАЙЛ_КЭША = os.path.join(_БАЗОВАЯ_ПАПКА, "prototype_cache.npz")

# Порог абсолютного сходства. Если max cos с любым in-scope прототипом ниже —
# сразу off-topic (отсекает совсем мусорные/абракадабровые запросы).
SCOPE_АБС_ПОРОГ = 0.50

# Margin между лучшим in-scope и лучшим off-scope прототипом. Если положительный
# (in-scope ближе) — запрос в скоупе. Это основной механизм scope-guard, потому
# что multilingual-e5 даёт неинформативно высокие cosine ~0.7 на любую пару.
SCOPE_MARGIN_ПОРОГ = 0.0

# Алиас для обратной совместимости (использовался в UI как "порог")
SCOPE_ПОРОГ_ПО_УМОЛЧАНИЮ = SCOPE_АБС_ПОРОГ

# Якоря «не наша область». Используются как декорация: вопрос off-topic, если
# его эмбеддинг ближе к этим, чем к прототипам субдоменов.
ОТРИЦАТЕЛЬНЫЕ_ЯКОРЯ = [
    "Спорт: футбол, хоккей, олимпийские игры, чемпионаты мира, спортивные команды и игроки.",
    "Кулинария и рецепты: как приготовить борщ, плов, пиццу, торт, рецепты блюд русской и мировой кухни.",
    "Путешествия и отдых: туризм, отпуск, страны, гостиницы, билеты, виза, достопримечательности.",
    "Литература и искусство: романы, стихи, писатели, художники, музыка, кино, театр, биографии.",
    "Бытовые вопросы и покупки: подарки, шопинг, советы по жизни, отношения, мода, красота.",
    "Политика и новости: выборы, экономика страны, правительство, международные отношения.",
    "История и география общего характера: столицы стран, исторические события не связанные с наукой.",
    "Развлечения и игры: видеоигры, настольные игры, телешоу, знаменитости, юмор, мемы.",
]


def _ключ_прототипов():
    """Хэш текстов прототипов и негативов — если изменились, перезальём кэш."""
    h = hashlib.sha1()
    for домен, суб, прото in все_субдомены():
        h.update(f"{домен}/{суб}\n{прото}\n".encode("utf-8"))
    for n in ОТРИЦАТЕЛЬНЫЕ_ЯКОРЯ:
        h.update(("NEG\n" + n + "\n").encode("utf-8"))
    return h.hexdigest()


def подготовить_прототипы(модель):
    """Считает (один раз) векторы прототипов субдоменов и отрицательных якорей.

    Возвращает: (метки, матрица_прототипов, матрица_негативов).
    Кэширует на диск; пересчитывает, только если изменилась таксономия или негативы.
    """
    ключ = _ключ_прототипов()
    if os.path.exists(_ФАЙЛ_КЭША):
        try:
            данные = np.load(_ФАЙЛ_КЭША, allow_pickle=True)
            if str(данные["ключ"]) == ключ:
                метки = [tuple(x) for x in данные["метки"].tolist()]
                негативы = данные["негативы"] if "негативы" in данные.files else None
                if негативы is not None:
                    return метки, данные["векторы"], негативы
        except Exception:
            pass

    метки = []
    тексты = []
    for домен, суб, прото in все_субдомены():
        метки.append((домен, суб))
        тексты.append("passage: " + прото)
    векторы = модель.encode(тексты, normalize_embeddings=True, show_progress_bar=False)
    негативы = модель.encode(
        ["passage: " + n for n in ОТРИЦАТЕЛЬНЫЕ_ЯКОРЯ],
        normalize_embeddings=True,
        show_progress_bar=False,
    )
    np.savez(
        _ФАЙЛ_КЭША,
        ключ=ключ,
        метки=np.array(метки, dtype=object),
        векторы=векторы,
        негативы=негативы,
    )
    return метки, векторы, негативы


def _распаковать_прототипы(модель, прототипы_arg):
    """Поддержка обоих API: прототипы как (метки, векторы) или (метки, векторы, негативы)."""
    if прототипы_arg is None:
        return подготовить_прототипы(модель)
    if len(прототипы_arg) == 3:
        return прототипы_arg
    # старый формат — догрузим
    return подготовить_прототипы(модель)


def классифицировать_текст(текст, модель, метки=None, прототипы=None, режим="passage", _негативы=None):
    """Возвращает (домен, субдомен, score) — top-1 по cosine similarity среди in-scope прототипов."""
    if метки is None or прототипы is None:
        метки, прототипы, _негативы = подготовить_прототипы(модель)

    префикс = "passage: " if режим == "passage" else "query: "
    вектор = модель.encode(префикс + текст, normalize_embeddings=True)
    скоры = прототипы @ вектор  # cosine, т.к. оба нормированы
    индекс = int(np.argmax(скоры))
    домен, суб = метки[индекс]
    return домен, суб, float(скоры[индекс])


def классифицировать_батч(тексты, модель, метки=None, прототипы=None, режим="passage", размер_батча=64, _негативы=None):
    """Версия для пакетной обработки чанков при ингесте."""
    if метки is None or прототипы is None:
        метки, прототипы, _негативы = подготовить_прототипы(модель)

    префикс = "passage: " if режим == "passage" else "query: "
    результаты = []
    for старт in range(0, len(тексты), размер_батча):
        батч = тексты[старт:старт + размер_батча]
        векторы = модель.encode(
            [префикс + т for т in батч],
            normalize_embeddings=True,
            show_progress_bar=False,
        )
        скоры = векторы @ прототипы.T  # (батч, прототипы)
        индексы = np.argmax(скоры, axis=1)
        макс_скоры = np.max(скоры, axis=1)
        for и, с in zip(индексы, макс_скоры):
            домен, суб = метки[int(и)]
            результаты.append((домен, суб, float(с)))
    return результаты


def проверить_scope(
    вопрос,
    модель,
    метки=None,
    прототипы=None,
    негативы=None,
    порог=None,
    margin_порог=None,
):
    """Scope-guard через margin-сравнение позитивных и негативных якорей.

    Запрос считается in-scope, если:
      1) max cos с in-scope прототипом ≥ SCOPE_АБС_ПОРОГ (отсекает абракадабру);
      2) (max in-scope) − (max off-scope) ≥ SCOPE_MARGIN_ПОРОГ.

    Возвращает (in_scope, домен, субдомен, абсолютный_score).
    """
    if метки is None or прототипы is None or негативы is None:
        # Поддержка вызова со старой сигнатурой подготовить_прототипы → tuple длины 2
        if isinstance(прототипы, tuple) and len(прототипы) == 2:
            метки, прототипы = прототипы
        else:
            метки, прототипы, негативы = подготовить_прототипы(модель)

    if порог is None:
        порог = SCOPE_АБС_ПОРОГ
    if margin_порог is None:
        margin_порог = SCOPE_MARGIN_ПОРОГ

    вектор = модель.encode("query: " + вопрос, normalize_embeddings=True)
    pos_скоры = прототипы @ вектор
    neg_скоры = негативы @ вектор if негативы is not None else np.array([0.0])

    лучший_pos_idx = int(np.argmax(pos_скоры))
    лучший_pos = float(pos_скоры[лучший_pos_idx])
    лучший_neg = float(np.max(neg_скоры))
    margin = лучший_pos - лучший_neg

    домен, суб = метки[лучший_pos_idx]
    in_scope = (лучший_pos >= порог) and (margin >= margin_порог)
    return in_scope, домен, суб, лучший_pos


