def test_C22v2_не_трогает_плашку_когда_нет_маркеров():
    """В чистом fallback-режиме (без маркеров) плашка должна остаться —
    она тут уместна."""
    sys.modules.pop("app", None)
    import app
    исходник = (
        "Хлор имеет формулу Cl2, относится к галогенам.\n\n"
        "*Это общеизвестное знание, в найденных фрагментах конкретного "
        "ответа не было.*"
    )
    # Эта функция вызывается только когда в ответе уже есть [N] маркеры,
    # поэтому если её случайно вызвать без них — плашку всё равно не
