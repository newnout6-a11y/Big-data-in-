def содержит_математику(текст):
    if any(с in _МАТЕМАТИЧЕСКИЕ_СИМВОЛЫ for с in текст):
        return True
    if re.search(r"\b[a-zA-Zα-ωΑ-Ω]\s*\([a-zA-Z0-9,\s]+\)\s*=", текст):
        return True
    if re.search(r"\b\w+\s*=\s*[\w\-+\d/·*().\[\]]{5,}", текст) and re.search(r"[_^]|\b\d+\b", текст):
        return True
    return False


